"""One showcase video (1920x1080): the dream + controller + the transformer's view of it.

  left:    the dreamed room (every pixel generated by the world model), pressed key below
  middle:  the 16x16 grid of codebook ids it predicted this frame (changed ids light up)
  right:   its memory: the strided past frames + anchor it attends to

  python render_showcase.py --wm runs/rope1/ckpts/wm_010000.pt --seed 7 --out runs/showcase_tweet.mp4
"""
import argparse
import time
import numpy as np
import torch
from PIL import Image, ImageDraw, ImageFont
from env import FireflyRoom
from dream import load, Dream
from vqvae import VQVAE
from videoutil import draw_keys, write_mp4

BG, PANEL, DIM, TEXT, AMBER = (8, 9, 13), (16, 18, 24), (70, 76, 90), (210, 212, 220), (242, 184, 75)
# a short "performance": (action, repeats)  0 stay 1 fwd 2 back 3 left 4 right
SCRIPT = [(0, 6), (4, 7), (1, 8), (3, 10), (1, 6), (0, 6), (4, 14), (1, 10), (2, 5), (3, 8),
          (1, 12), (0, 8), (4, 9), (1, 8), (3, 12), (0, 6)]


def font(size):
    for f in ["/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
              "/System/Library/Fonts/Menlo.ttc"]:
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            pass
    return ImageFont.load_default()


def up(img, size):
    return Image.fromarray(img).resize((size, size), Image.NEAREST)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vqvae", default="runs/vqvae_ft/vqvae.pt")
    ap.add_argument("--wm", default="runs/rope1/ckpts/wm_010000.pt")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", default="runs/showcase_tweet.mp4")
    ap.add_argument("--fps", type=int, default=12)
    a = ap.parse_args()

    vq, wm = load(a.vqvae, a.wm)
    n_params = sum(p.numel() for p in wm.parameters()) / 1e6
    env = FireflyRoom(res=64, seed=a.seed, n_boxes=3, n_flies=2)
    frames, acts = [env.reset()], []
    for _ in range(7):
        acts.append(0); frames.append(env.step(0))
    dream = Dream(vq, wm, frames, acts, passes=1, temperature=0)

    # mean colour of each codeword (decode each code as a flat 16x16 grid) -> tint for the id grid
    with torch.no_grad():
        ids = torch.arange(512, device="cuda")[:, None, None].expand(512, 16, 16)
        code_rgb = torch.cat([VQVAE.to_image(vq.decode(ids[i:i + 64])) for i in range(0, 512, 64)])
        code_rgb = code_rgb.float().mean((1, 2)).cpu().numpy()                          # (512, 3)

    f_title, f_sub, f_id, f_small = font(34), font(22), font(15), font(17)
    W, H, S, CELL = 1920, 1080, 800, 50
    gx0, gy0 = 40 + S + 40, 140
    prev_tok = dream.hist[-1].cpu().numpy()
    actions = [x for act, n in SCRIPT for x in [act] * n]
    video, ms = [], []
    for step, action in enumerate(actions):
        torch.cuda.synchronize(); t0 = time.time()
        img = dream.step(action)
        torch.cuda.synchronize(); ms.append((time.time() - t0) * 1000)
        tok = dream.hist[-1].cpu().numpy()

        canvas = Image.new("RGB", (W, H), BG)
        d = ImageDraw.Draw(canvas)
        d.text((40, 30), "A neural network is rendering this room", fill=TEXT, font=f_title)
        d.text((40, 76), f"world model · {n_params:.1f}M params · every pixel predicted from 256 tokens · "
                         f"you drive the flashlight", fill=DIM, font=f_sub)

        # 1) the dream
        canvas.paste(up(img, S), (40, 140 - 0))
        d.rectangle([40, 140, 40 + S, 140 + S], outline=(40, 44, 56), width=2)
        keys = draw_keys(action, size=40)
        canvas.paste(keys, (40 + (S - keys.width) // 2 - 0, 140 + S + 8))

        # 2) the codeword grid
        d.text((gx0, 110), "what the transformer predicts: 16×16 codebook ids", fill=DIM, font=f_small)
        for i in range(256):
            r, c = divmod(i, 16)
            x, y = gx0 + c * CELL, gy0 + r * CELL
            col = code_rgb[tok[i]]
            bright = 0.25 + 0.75 * col / 255
            fill = tuple(int(18 + 0.35 * v) for v in col)
            changed = tok[i] != prev_tok[i]
            d.rectangle([x + 1, y + 1, x + CELL - 2, y + CELL - 2], fill=fill,
                        outline=AMBER if changed else (30, 33, 42), width=2 if changed else 1)
            txt_col = AMBER if changed else tuple(int(110 + 145 * b) for b in bright)
            d.text((x + CELL / 2, y + CELL / 2), str(tok[i]), fill=txt_col, font=f_id, anchor="mm")
        n_changed = int((tok != prev_tok).sum())
        d.text((gx0, gy0 + 16 * CELL + 14), f"{n_changed:3d}/256 ids changed this frame  ·  "
               f"1 forward pass  ·  {np.mean(ms[-20:]):.0f} ms", fill=TEXT, font=f_small)
        prev_tok = tok

        # 3) memory strip: what it attends to
        mx = gx0 + 16 * CELL + 40
        d.text((mx, 110), "its memory", fill=DIM, font=f_small)
        t = len(dream.hist) - 1
        slots = [("anchor", dream.anchor)] + [(f"t-{o}", dream.hist[max(t - o, 0)]) for o in wm.offsets[:-1]]
        th, gap = 86, 6
        with torch.no_grad():
            thumbs = VQVAE.to_image(vq.decode(torch.stack([s for _, s in slots]).view(-1, 16, 16))).cpu().numpy()
        for j, ((label, _), timg) in enumerate(zip(slots, thumbs)):
            y = gy0 + j * (th + gap)
            canvas.paste(up(timg, th), (mx, y))
            d.text((mx + th + 10, y + th / 2), label, fill=AMBER if label == "anchor" else TEXT,
                   font=f_small, anchor="lm")
        video.append(np.asarray(canvas))
    write_mp4(video, a.out, fps=a.fps)
    print(f"wrote {a.out}: {len(video)} frames, {np.mean(ms):.1f} ms per dream step on {torch.cuda.get_device_name(0)}")


if __name__ == "__main__":
    main()
